// Wires product photos into the site by file name — no code edits needed.
//
//   app/public/images/products/<category-slug>/<product-slug>.(webp|jpg|jpeg|png|avif)
//   app/public/images/products/<category-slug>/cover.(webp|jpg|...)   ← optional category cover
//
// Writes lib/product-images.ts (static imports, so Next optimises them) and a README.md in each
// category folder listing the expected file names. Runs automatically before `npm run build`;
// run `npm run images` after adding photos while `npm run dev` is running.
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const DIR = path.join(ROOT, "app/public/images/products");
const OUT = path.join(ROOT, "lib/product-images.ts");
const EXT = [".webp", ".jpg", ".jpeg", ".png", ".avif"];
const catalogue = JSON.parse(fs.readFileSync(path.join(ROOT, "data/catalogue.json"), "utf8"));

const imports = [];
const entries = [];
let found = 0;
let total = 0;

for (const cat of catalogue) {
  const folder = path.join(DIR, cat.slug);
  fs.mkdirSync(folder, { recursive: true });
  const files = fs.readdirSync(folder);
  const pick = (base) => files.find((f) => EXT.includes(path.extname(f).toLowerCase()) && path.basename(f, path.extname(f)).toLowerCase() === base);

  const add = (key, file) => {
    const id = `img${imports.length}`;
    imports.push(`import ${id} from "@/app/public/images/products/${cat.slug}/${file}";`);
    entries.push(`  "${key}": ${id},`);
  };

  const cover = pick("cover");
  if (cover) add(`${cat.slug}/cover`, cover);

  const lines = [
    `# ${cat.number} · ${cat.name}`,
    "",
    "Drop product photos here named exactly as below (.webp, .jpg, .png or .avif; square works best).",
    "Optional: `cover.webp` for the category card. Then run `npm run images` (it also runs before every build).",
    "",
    `- ${cover ? "✅" : "⬜"} cover — category cover (optional; otherwise the first product photo is used)`,
  ];
  for (const item of cat.items) {
    total++;
    const file = pick(item.slug);
    if (file) {
      found++;
      add(`${cat.slug}/${item.slug}`, file);
    }
    lines.push(`- ${file ? "✅" : "⬜"} \`${item.slug}\` — ${item.name}`);
  }
  fs.writeFileSync(path.join(folder, "README.md"), lines.join("\n") + "\n");
}

fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/sync-product-images.mjs — do not edit. Run \`npm run images\` after adding photos.
import type { StaticImageData } from "next/image";
${imports.join("\n")}

/** "<category-slug>/<product-slug>" or "<category-slug>/cover" → photo. */
export const PRODUCT_IMAGES: Record<string, StaticImageData> = {
${entries.join("\n")}
};
`,
);
console.log(`product images: ${found}/${total} products have photos`);
